-- A API usa a chave service_role somente no servidor Netlify; nunca no navegador.
create table if not exists public.items (
  id text primary key,
  name text not null,
  price numeric(12,2) not null default 0,
  img text not null default ''
);
create table if not exists public.sets (
  id bigint generated by default as identity primary key,
  name text not null,
  icon text,
  price numeric(12,2) not null default 0
);
create table if not exists public.set_items (
  set_id bigint not null references public.sets(id) on delete cascade,
  item_id text not null references public.items(id) on delete cascade,
  sort_order integer not null default 0,
  primary key(set_id,item_id)
);
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null,
  username_lc text not null unique,
  salt text not null,
  pw_hash text not null,
  is_admin boolean not null default false,
  created double precision not null
);
create table if not exists public.sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  expires double precision not null
);
create table if not exists public.user_state (
  user_id bigint primary key references public.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated double precision not null
);

-- As tabelas são acessadas pelo backend Netlify com service_role.
-- Bloqueia leitura/escrita direta via chave pública anônima.
alter table public.items enable row level security;
alter table public.sets enable row level security;
alter table public.set_items enable row level security;
alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.user_state enable row level security;
revoke all on public.items, public.sets, public.set_items, public.users, public.sessions, public.user_state from anon, authenticated;

